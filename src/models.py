def train_salary_model(df: pd.DataFrame, X_skills: csr_matrix, skill_names: List[str],
                       models_dir: Path = MODELS_DIR, min_rows: int = MIN_SALARY_ROWS,
                       progress: Optional[Callable[[str], None]] = None) -> dict:
    """Predict log(annual salary) from skills + role + experience group."""
    result = {"task": "salary_regression", "status": "skipped", "limitations": SALARY_LIMITATIONS}
    mask = df["salary_annual"].notna().to_numpy()
    n = int(mask.sum())
    result["n_rows_with_salary"] = n
    if n < min_rows:
        result["reason"] = f"Only {n} postings have a usable salary (need >= {min_rows})."
        return result

    sub = df.loc[mask]
    y = np.log1p(sub["salary_annual"].to_numpy(dtype=float))
    enc = OneHotEncoder(handle_unknown="ignore")
    cat = enc.fit_transform(sub[["role", "level_group"]].astype(str))
    X = hstack([_f32(X_skills[mask]), cat], format="csr")
    feature_names = [f"skill: {s}" for s in skill_names] + list(enc.get_feature_names_out())
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.2, random_state=RANDOM_STATE)

    candidates = {
        "Baseline (mean)": DummyRegressor(strategy="mean"),
        "Ridge": Ridge(alpha=5.0),
        "Random Forest": RandomForestRegressor(n_estimators=100, max_depth=20, min_samples_leaf=3,
                                               n_jobs=-1, random_state=RANDOM_STATE),
    }
    cv_n = min(X_tr.shape[0], 15_000)          # CV on a slice keeps big datasets fast (split is already shuffled)
    X_cv, y_cv = X_tr[:cv_n], y_tr[:cv_n]
    cv_out = []
    for name, model in candidates.items():
        if name.startswith("Baseline"):
            continue
        _say(progress, f"Salary model: cross-validating {name}")
        try:
            sc = cross_val_score(model, X_cv, y_cv, cv=3, scoring="neg_mean_absolute_error")
            cv_out.append({"model": name, "cv_mae_log": float(-sc.mean()), "error": None})
        except Exception as exc:
            cv_out.append({"model": name, "cv_mae_log": np.nan, "error": str(exc)[:200]})
    cv_df = pd.DataFrame(cv_out)
    good = cv_df[cv_df["cv_mae_log"].notna()]
    if good.empty:
        result["reason"] = "All salary models failed during cross-validation."
        result["cv_results"] = cv_df.to_dict(orient="records")
        return result
    best_name = good.sort_values("cv_mae_log")["model"].iloc[0]
    best = candidates[best_name].fit(X_tr, y_tr)
    base = candidates["Baseline (mean)"].fit(X_tr, y_tr)

    def metrics(model):
        p = model.predict(X_te)
        return {"mae_usd": float(mean_absolute_error(np.expm1(y_te), np.expm1(p))),
                "rmse_usd": float(np.sqrt(mean_squared_error(np.expm1(y_te), np.expm1(p)))),
                "r2_log": float(r2_score(y_te, p))}

    top = []
    if hasattr(best, "coef_"):
        order = np.argsort(-np.abs(best.coef_))[:20]
        top = [{"feature": feature_names[j], "weight": float(best.coef_[j])} for j in order]
    elif hasattr(best, "feature_importances_"):
        order = np.argsort(-best.feature_importances_)[:20]
        top = [{"feature": feature_names[j], "weight": float(best.feature_importances_[j])} for j in order]

    joblib.dump({"model": best, "encoder": enc, "skill_names": skill_names}, models_dir / "salary_model.joblib", compress=3)
    result.update({"status": "ok", "best_model": best_name, "n_train": int(X_tr.shape[0]),
                   "n_test": int(X_te.shape[0]), "cv_results": cv_df.to_dict(orient="records"),
                   "test_metrics": metrics(best), "baseline_metrics": metrics(base),
                   "top_features": top, "median_salary_usd": float(np.median(np.expm1(y)))})
    result["beats_baseline"] = bool(result["test_metrics"]["mae_usd"] < result["baseline_metrics"]["mae_usd"])
    return result
