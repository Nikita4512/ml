"""Machine-learning models (all metrics are computed live from YOUR data).

1) Role-family classifier  : job description + extracted skills -> role family
2) Salary regressor        : skills + role + level -> annual salary (only if enough salary rows)

Honest-evaluation features
  * stratified train/test split; test set never used for model selection
  * model selection by cross-validation on training data only
  * majority-class / mean baselines reported next to every model
  * limitations are written into the result dict and shown in the UI

Known limitation (shown to the user): role labels come from title keyword rules,
and descriptions often repeat the job title, so classification accuracy can look
optimistic. The title column itself is NOT used as a feature.
"""
from __future__ import annotations

import time
from pathlib import Path
from typing import Callable, Dict, List, Optional

import joblib
import numpy as np
import pandas as pd
from scipy.sparse import csr_matrix, hstack
from sklearn.dummy import DummyClassifier, DummyRegressor
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression, Ridge
from sklearn.metrics import (accuracy_score, classification_report, confusion_matrix, f1_score,
                             mean_absolute_error, mean_squared_error, r2_score)
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split
from sklearn.preprocessing import OneHotEncoder
from sklearn.svm import LinearSVC

from .config import (CV_MAX_ROWS, MAX_TRAIN_ROWS, MIN_CLASS_N, MIN_SALARY_ROWS, MODELS_DIR,
                     RANDOM_STATE)
from .role_mapper import LABEL_CAVEAT

ROLE_LIMITATIONS = [
    "Labels come from title keyword rules, so the model learns to reproduce those rules from descriptions.",
    "Descriptions often mention the job title, so accuracy can be optimistic; the title column is not used as a feature.",
    "Only postings whose title matched a tech role family are used; 'Other' titles are excluded.",
    # --- weak-label transparency ---
    "Role labels are WEAK LABELS generated by keyword rules applied to job titles, not human-validated ground truth.",
    "If the job description mentions the job title (which is common), classification can look optimistically high "
    "because both labels and features derive from the same title keywords.",
    # --- CV note ---
    "CV is performed on TF-IDF features pre-computed from the training split. For fully pipeline-based CV, "
    "a sklearn Pipeline would be needed. This is a known limitation.",
]
SALARY_LIMITATIONS = [
    "Only postings that list salary are used (a self-selected subset).",
    "Salary is converted to an approximate yearly figure; part-time/hourly conversions are rough.",
    "Skill-salary relationships are associations, not causal effects.",
    "Currency is not filtered: figures are labelled USD but the LinkedIn data is assumed to be mostly USD.",
]


def _say(progress: Optional[Callable], msg: str) -> None:
    if progress:
        progress(msg)


def _f32(x) -> csr_matrix:
    return csr_matrix(x, dtype=np.float32)


# ===========================================================================
def train_role_classifier(df: pd.DataFrame, X_skills: csr_matrix, skill_names: List[str],
                          models_dir: Path = MODELS_DIR, max_rows: int = MAX_TRAIN_ROWS,
                          cv_rows: int = CV_MAX_ROWS, min_class_n: int = MIN_CLASS_N,
                          progress: Optional[Callable[[str], None]] = None) -> dict:
    """Train + evaluate the role-family classifier. Returns a JSON-friendly result dict."""
    result = {"task": "role_family_classification", "status": "skipped", "limitations": ROLE_LIMITATIONS}
    roles = df["role"]
    counts = roles[roles != "Other"].value_counts()
    keep = counts[counts >= min_class_n].index.tolist()
    result["dropped_classes"] = {r: int(c) for r, c in counts.items() if c < min_class_n}
    if len(keep) < 2:
        result["reason"] = (f"Need at least 2 role classes with >= {min_class_n} postings; "
                            f"found {len(keep)} (counts: {counts.to_dict()}).")
        return result

    idx = np.where(roles.isin(keep).to_numpy())[0]
    if len(idx) > max_rows:
        idx, _ = train_test_split(idx, train_size=max_rows, stratify=roles.iloc[idx], random_state=RANDOM_STATE)
    y = roles.iloc[idx].to_numpy()
    Xs = X_skills[idx]
    texts = df["description"].iloc[idx].to_numpy()
    tr, te = train_test_split(np.arange(len(y)), test_size=0.2, stratify=y, random_state=RANDOM_STATE)

    _say(progress, "Role model: building TF-IDF features")
    tfidf = TfidfVectorizer(max_features=8000, ngram_range=(1, 2), min_df=5, max_df=0.7,
                            stop_words="english", sublinear_tf=True, dtype=np.float32)
    # LEAKAGE CHECK: tfidf is fit only on texts[tr] (training indices)
    T_tr = tfidf.fit_transform(texts[tr])                 # fitted on TRAIN only
    T_te = tfidf.transform(texts[te])
    X_tr = hstack([_f32(Xs[tr]), T_tr], format="csr")
    X_te = hstack([_f32(Xs[te]), T_te], format="csr")
    y_tr, y_te = y[tr], y[te]

    candidates = {
        "Baseline (most frequent)": DummyClassifier(strategy="most_frequent"),
        "Logistic Regression": LogisticRegression(max_iter=300, class_weight="balanced"),
        "Linear SVM": LinearSVC(class_weight="balanced"),
        "Random Forest": RandomForestClassifier(n_estimators=100, max_depth=30, n_jobs=-1,
                                                class_weight="balanced_subsample", random_state=RANDOM_STATE),
    }
    # ---- model selection by CV on a (capped) slice of the TRAINING data
    if len(y_tr) > cv_rows:
        sub, _ = train_test_split(np.arange(len(y_tr)), train_size=cv_rows, stratify=y_tr, random_state=RANDOM_STATE)
    else:
        sub = np.arange(len(y_tr))
    min_count = int(pd.Series(y_tr[sub]).value_counts().min())
    n_splits = min(3, min_count)
    cv_rows_out = []
    for name, model in candidates.items():
        _say(progress, f"Role model: cross-validating {name}")
        t0 = time.time()
        try:
            if n_splits >= 2:
                skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=RANDOM_STATE)
                sc = cross_val_score(model, X_tr[sub], y_tr[sub], cv=skf, scoring="f1_macro")
                cv_rows_out.append({"model": name, "cv_macro_f1": float(sc.mean()), "cv_std": float(sc.std()),
                                    "seconds": round(time.time() - t0, 1), "error": None})
            else:
                cv_rows_out.append({"model": name, "cv_macro_f1": np.nan, "cv_std": np.nan,
                                    "seconds": 0, "error": "too few samples in smallest class for CV"})
        except Exception as exc:                           # keep going if one model fails
            cv_rows_out.append({"model": name, "cv_macro_f1": np.nan, "cv_std": np.nan,
                                "seconds": round(time.time() - t0, 1), "error": str(exc)[:200]})
    cv_df = pd.DataFrame(cv_rows_out)
    ok = cv_df[(cv_df["model"] != "Baseline (most frequent)") & cv_df["cv_macro_f1"].notna()]
    best_name = ok.sort_values("cv_macro_f1", ascending=False)["model"].iloc[0] if len(ok) else "Logistic Regression"

    # ---- final fit + honest TEST evaluation
    _say(progress, f"Role model: fitting {best_name} and evaluating on held-out test set")
    best = candidates[best_name]
    best.fit(X_tr, y_tr)
    pred = best.predict(X_te)
    base = DummyClassifier(strategy="most_frequent").fit(X_tr, y_tr).predict(X_te)
    classes = [str(c) for c in best.classes_]
    report = classification_report(y_te, pred, output_dict=True, zero_division=0)
    cm = confusion_matrix(y_te, pred, labels=best.classes_)

    feature_names = [f"skill: {s}" for s in skill_names] + list(tfidf.get_feature_names_out())
    top_features = {}
    if hasattr(best, "coef_") and best.coef_.shape[0] == len(classes):
        for i, cls in enumerate(classes):
            top = np.argsort(-best.coef_[i])[:12]
            top_features[cls] = [feature_names[j] for j in top]
    elif hasattr(best, "feature_importances_"):
        top = np.argsort(-best.feature_importances_)[:25]
        top_features["(all classes)"] = [feature_names[j] for j in top]

    bundle = {"tfidf": tfidf, "model": best, "classes": classes, "skill_names": skill_names}
    models_dir.mkdir(parents=True, exist_ok=True)
    joblib.dump(bundle, models_dir / "role_classifier.joblib", compress=3)

    result.update({
        "status": "ok", "best_model": best_name, "classes": classes,
        "n_train": int(len(tr)), "n_test": int(len(te)),
        "class_counts": pd.Series(y).value_counts().to_dict(),
        "cv_results": cv_df.to_dict(orient="records"), "cv_folds": n_splits, "cv_rows_used": int(len(sub)),
        "test_accuracy": float(accuracy_score(y_te, pred)),
        "test_macro_f1": float(f1_score(y_te, pred, average="macro")),
        "test_weighted_f1": float(f1_score(y_te, pred, average="weighted")),
        "baseline_accuracy": float(accuracy_score(y_te, base)),
        "majority_class_baseline_accuracy": float(accuracy_score(y_te, base)),  # explicit alias
        "baseline_macro_f1": float(f1_score(y_te, base, average="macro")),
        "per_class_report": {k: v for k, v in report.items() if k in classes},
        "confusion_matrix": cm.tolist(), "top_features": top_features,
        "model_path": str(models_dir / "role_classifier.joblib"),
        # --- weak-label transparency fields ---
        "label_type": "rule_based_weak_label",
        "label_caveat": LABEL_CAVEAT,
        "human_validated": False,
        "evaluation_note": (
            "Performance measured against heuristic (rule-based) labels. "
            "Human-validated evaluation requires manually labelled test data."
        ),
        "cv_note": (
            "Cross-validation for model selection uses pre-computed TF-IDF features "
            "(fit on training split only). Raw-text CV through the full pipeline would "
            "require a sklearn Pipeline — see known limitation."
        ),
        "human_label_evaluation_note": (
            "To evaluate against human labels: provide a CSV with columns [job_id, human_role] "
            "and pass it as `human_labels_df` parameter (not yet implemented — see limitations)."
        ),
    })
    result["beats_baseline"] = bool(result["test_macro_f1"] > result["baseline_macro_f1"])
    return result


def predict_roles(bundle: dict, texts: List[str], X_skills: csr_matrix) -> np.ndarray:
    """Use a saved role-classifier bundle (see load_role_bundle) on new postings."""
    X = hstack([_f32(X_skills), bundle["tfidf"].transform(texts)], format="csr")
    return bundle["model"].predict(X)


def load_role_bundle(models_dir: Path = MODELS_DIR) -> Optional[dict]:
    path = models_dir / "role_classifier.joblib"
    return joblib.load(path) if path.exists() else None


