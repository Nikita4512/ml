"""Rule-based mapping of a job TITLE to a tech role family.

These rules are transparent heuristics (not learned). First matching rule wins,
so the order below matters. Titles that match nothing become "Other" and are
excluded from the role classifier and the role skill profiles.
"""
from __future__ import annotations

import pandas as pd

# ---------------------------------------------------------------------------
# Transparency constants — surfaced in the UI and in model result dicts
# ---------------------------------------------------------------------------
UNMAPPED_TITLE_LABEL = "Other"
LABEL_CAVEAT = (
    "Role labels are generated by keyword rules applied to job titles. "
    "They are weak labels, not human-validated ground truth."
)

# (role, include-regex, exclude-regex or None)   - use non-capturing groups (?:...)
ROLE_RULES = [
    ("Machine Learning / AI Engineer",
     r"machine learning|\bml\b|\bai\b|artificial intelligence|deep learning|\bnlp\b|computer vision|\bllm|generative|mlops|applied scientist|research scientist",
     None),
    ("Data Scientist", r"data scien|decision scien|statistician|biostatistic|quantitative (?:analyst|researcher)", None),
    ("Data Engineer", r"data engineer|\betl\b|big data|data platform|analytics engineer|data architect|data warehouse|databricks|snowflake", None),
    ("Data Analyst / BI", r"data analy|business intelligence|\bbi (?:developer|analyst|engineer)|reporting analyst|insights analyst|analytics|business analyst", None),
    ("Cybersecurity Specialist", r"cyber|infosec|penetration|security (?:engineer|analyst|architect|specialist|consultant)|\bsoc analyst|vulnerab|information security",
     r"guard|officer|loss prevention|patrol|armed|social security|security supervisor"),
    ("DevOps / Cloud Engineer", r"devops|devsecops|\bcloud\b|site reliability|\bsre\b|platform engineer|infrastructure engineer|kubernetes", r"cloud kitchen"),
    ("Database Administrator", r"database (?:admin|administrator|engineer|developer)|\bdba\b|sql developer", None),
    ("QA / Test Engineer", r"\bqa\b|\bsdet\b|software test|test automation|automation engineer|test engineer|quality assurance (?:engineer|analyst|tester)",
     r"pharma|clinical|food|manufactur|laborator"),
    ("Mobile Developer", r"android|\bios\b|mobile (?:developer|engineer|app)|flutter|react native", None),
    ("Frontend / Full-Stack Developer", r"front.?end|full.?stack|web developer|ui developer|ui engineer|web engineer|\breact\b|\bangular\b|javascript|\bvue\b", None),
    ("UX / UI Designer", r"\bux\b|ui/ux|product designer|ui designer|user experience|user interface designer", None),
    ("Software Engineer (General/Backend)",
     r"software|back.?end|\bsde\b|programmer|application developer|api developer|(?:java|python|\.net|c\+\+|c#|php|ruby|golang|node(?:\.js)?) developer|developer in test", None),
    ("IT Support / Systems Admin", r"help ?desk|it support|technical support|desktop support|system(?:s)? administrator|sysadmin|network (?:engineer|administrator)|it technician|service desk|it specialist", None),
]
ROLE_LIST = [r[0] for r in ROLE_RULES]


def map_roles(titles: pd.Series) -> pd.Series:
    """Vectorised title -> role family. Unmatched titles -> "Other"."""
    t = titles.fillna("").astype(str).str.lower()
    roles = pd.Series("Other", index=titles.index, dtype=object)
    unassigned = pd.Series(True, index=titles.index)
    for role, include, exclude in ROLE_RULES:
        hit = t.str.contains(include, regex=True, na=False)
        if exclude:
            hit &= ~t.str.contains(exclude, regex=True, na=False)
        hit &= unassigned
        roles[hit] = role
        unassigned &= ~hit
    return roles


# ---------------------------------------------------------------------------
# Confidence tiers for each role family
# "High"  : specific technical patterns (ML/AI, Data Scientist, Cybersecurity)
# "Medium": broader keyword patterns (Data Analyst/BI, Frontend, Mobile)
# "Low"   : catch-all (Software Engineer General/Backend)
# "Unmapped": title matched nothing (-> UNMAPPED_TITLE_LABEL)
# ---------------------------------------------------------------------------
_CONFIDENCE_MAP: dict[str, str] = {
    "Machine Learning / AI Engineer":    "High",
    "Data Scientist":                    "High",
    "Cybersecurity Specialist":          "High",
    "Data Engineer":                     "Medium",
    "Data Analyst / BI":                 "Medium",
    "Frontend / Full-Stack Developer":   "Medium",
    "Mobile Developer":                  "Medium",
    "DevOps / Cloud Engineer":           "Medium",
    "Database Administrator":            "Medium",
    "QA / Test Engineer":                "Medium",
    "UX / UI Designer":                  "Medium",
    "IT Support / Systems Admin":        "Medium",
    "Software Engineer (General/Backend)": "Low",
}


def map_roles_with_confidence(titles: pd.Series) -> pd.DataFrame:
    """Return a DataFrame with role-mapping metadata for each title.

    Columns
    -------
    role               : mapped role family, or UNMAPPED_TITLE_LABEL
    mapping_confidence : "High" | "Medium" | "Low" | "Unmapped"
    is_ambiguous       : True when a second rule would also match after removing
                         the first-matching rule (title can plausibly belong to
                         two role families)
    label_type         : always "rule_based_weak_label" — never "ground_truth"
    """
    t = titles.fillna("").astype(str).str.lower()

    # --- first-match role (same logic as map_roles) -------------------------
    roles = pd.Series(UNMAPPED_TITLE_LABEL, index=titles.index, dtype=object)
    first_match_rule_idx = pd.Series(-1, index=titles.index, dtype=int)
    unassigned = pd.Series(True, index=titles.index)
    for rule_idx, (role, include, exclude) in enumerate(ROLE_RULES):
        hit = t.str.contains(include, regex=True, na=False)
        if exclude:
            hit &= ~t.str.contains(exclude, regex=True, na=False)
        hit &= unassigned
        roles[hit] = role
        first_match_rule_idx[hit] = rule_idx
        unassigned &= ~hit

    # --- ambiguity check: does any *other* rule also match? -----------------
    is_ambiguous = pd.Series(False, index=titles.index)
    for i in titles.index:
        my_rule = first_match_rule_idx.at[i]
        if my_rule == -1:
            # Unmapped — not ambiguous by definition
            continue
        ti = t.at[i]
        for rule_idx, (_, include, exclude) in enumerate(ROLE_RULES):
            if rule_idx == my_rule:
                continue
            if not pd.Series([ti]).str.contains(include, regex=True, na=False).iloc[0]:
                continue
            if exclude and pd.Series([ti]).str.contains(exclude, regex=True, na=False).iloc[0]:
                continue
            # A second rule matched -> ambiguous
            is_ambiguous.at[i] = True
            break

    # --- confidence tier ----------------------------------------------------
    mapping_confidence = roles.map(lambda r: _CONFIDENCE_MAP.get(r, "Unmapped"))

    return pd.DataFrame({
        "role":               roles,
        "mapping_confidence": mapping_confidence,
        "is_ambiguous":       is_ambiguous,
        "label_type":         "rule_based_weak_label",
    }, index=titles.index)
